/* Writes assets/manifest.js, a plain script that declares what is in
   each asset folder.

   The page reads folders live from serve.js, which is what lets a file
   dropped into assets/art/ appear with no code change. But a page
   opened straight off disk, as file://index.html, has no server to ask:
   every listing comes back empty and the whole page reports no samples
   with a clean console. A static deploy has the same problem.

   So the listing is also baked here. A <script> tag loads from file://
   where fetch() will not, and the page falls back to it whenever the
   API cannot be reached.

   Run after adding or renaming assets:  node build-manifest.js         */

const fs = require("fs");
const path = require("path");

const ROOT = __dirname;
const DIR = path.join(ROOT, "assets");
const IMAGES = /\.(jpe?g|png|webp|gif|avif|mp4|webm)$/i;

const out = {};
for (const name of fs.readdirSync(DIR).sort()) {
  const full = path.join(DIR, name);
  if (!fs.statSync(full).isDirectory()) continue;
  if (name.startsWith("_") || name.startsWith(".")) continue;   /* _unused, _grab */
  const files = fs.readdirSync(full)
    .filter(f => IMAGES.test(f) && !f.startsWith("."))
    .sort();
  if (files.length) out[name] = files;
}

const body = Object.entries(out)
  .map(([k, v]) => `  ${JSON.stringify(k)}: [\n` +
    v.map(f => `    ${JSON.stringify(f)}`).join(",\n") + `\n  ]`)
  .join(",\n");

fs.writeFileSync(path.join(DIR, "manifest.js"),
  `/* Generated by build-manifest.js. Do not edit by hand.\n` +
  `   Regenerate after changing anything in assets/:  node build-manifest.js */\n` +
  `window.ASSETS = {\n${body}\n};\n`);

const total = Object.values(out).reduce((n, v) => n + v.length, 0);
console.log(`assets/manifest.js: ${Object.keys(out).length} folders, ${total} files`);
for (const [k, v] of Object.entries(out)) console.log(`  ${k.padEnd(10)} ${v.length}`);
